// Regenerates extension/prompt.js from DEFAULT_SYSTEM_PROMPT and src/extension/extensionData.ts
// from every file in extension/. Run: node scripts/sync-extension.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ext = path.join(root, 'extension');

const presets = fs.readFileSync(path.join(root, 'src/data/presets.ts'), 'utf8');
const m = presets.match(/DEFAULT_SYSTEM_PROMPT = `([\s\S]*?)`;/);
if (!m) throw new Error('DEFAULT_SYSTEM_PROMPT not found');
const base = new Function('return `' + m[1] + '`')();

const tpl = fs.readFileSync(path.join(ext, 'prompt.js.tpl'), 'utf8');
fs.writeFileSync(path.join(ext, 'prompt.js'), tpl.replace('__BASE_PROMPT__', JSON.stringify(base)));

const TEXT = /\.(js|json|html|css|md)$/;
const files = {};
for (const f of fs.readdirSync(ext).sort()) {
  if (TEXT.test(f)) files[f] = fs.readFileSync(path.join(ext, f), 'utf8');
}
const out =
  '// AUTO-GENERATED by scripts/sync-extension.mjs from the extension/ folder. Do not edit.\n' +
  'export const EXTENSION_TEXT_FILES: Record<string, string> = ' +
  JSON.stringify(files, null, 1) + ';\n';
fs.mkdirSync(path.join(root, 'src/extension'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/extension/extensionData.ts'), out);
console.log('synced', Object.keys(files).length, 'files');
